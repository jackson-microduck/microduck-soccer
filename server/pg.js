import pg from 'pg'

const ID_TABLES = new Set(['users', 'clubs', 'challenges', 'club_invites', 'notifications', 'matches', 'reports', 'chat_messages', 'feedback', 'feedback_replies', 'direct_messages'])

export function translateSql(sql) {
  let text = String(sql).trim()
  const ignore = /^INSERT\s+OR\s+IGNORE\s+/i.test(text)
  text = text.replace(/^INSERT\s+OR\s+(?:IGNORE|REPLACE)\s+/i, 'INSERT ')
  text = text.replace(/(\b[\w.]+)\s*=\s*\?\s*COLLATE\s+NOCASE/gi, 'LOWER($1) = LOWER(?)')
  text = text.replace(/(\b[\w.]+)\s+LIKE\s+\?\s*COLLATE\s+NOCASE/gi, 'LOWER($1) LIKE LOWER(?)')
  text = text.replace(/ORDER\s+BY\s+([\w.]+)\s+COLLATE\s+NOCASE/gi, 'ORDER BY LOWER($1)')
  text = text.replace(/\s+COLLATE\s+NOCASE/gi, '')
  let n = 0
  text = text.replace(/\?/g, () => `$${++n}`)
  if (ignore && !/\bON\s+CONFLICT\b/i.test(text)) text += ' ON CONFLICT DO NOTHING'
  return text
}

export function pgSchema(sqliteSchema) {
  return sqliteSchema.replace(/INTEGER PRIMARY KEY/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/ COLLATE NOCASE/g, '')
}

function withReturning(original, translated) {
  if (!/^insert\s+/i.test(original) || /\breturning\b/i.test(translated)) return translated
  const table = original.match(/insert\s+(?:or\s+\w+\s+)?into\s+(\w+)/i)?.[1]
  if (!table || !ID_TABLES.has(table)) return translated
  return `${translated} RETURNING id`
}

export function sslFor(url) {
  if (/sslmode=disable/i.test(url)) return false
  return { rejectUnauthorized: false }
}

export function poolConfig(url) {
  return {
    connectionString: url,
    ssl: sslFor(url),
    max: 4,
    idleTimeoutMillis: 10_000,
  }
}

export async function openPostgres(url, queryable) {
  const pool = queryable || new pg.Pool(poolConfig(url))
  pg.types.setTypeParser(20, (value) => Number(value))
  const db = {
    driver: 'postgres',
    async exec(sql) {
      const parts = pgSchema(sql).split(';').map((part) => part.trim()).filter(Boolean)
      for (const part of parts) await pool.query(part)
    },
    prepare(sql) {
      const text = withReturning(sql, translateSql(sql))
      return {
        async get(...params) {
          const res = await pool.query(text, params)
          return res.rows[0]
        },
        async all(...params) {
          const res = await pool.query(text, params)
          return res.rows
        },
        async run(...params) {
          const res = await pool.query(text, params)
          return { lastInsertRowid: res.rows[0]?.id ?? 0, changes: res.rowCount }
        },
      }
    },
    async close() {
      if (!queryable) await pool.end()
    },
  }
  return db
}
