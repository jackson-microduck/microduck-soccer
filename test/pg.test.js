import test from 'node:test'
import assert from 'node:assert/strict'
import { pgSchema, poolConfig, sslFor, translateSql } from '../server/pg.js'
import { SCHEMA } from '../server/db.js'

test('sqlite queries translate to postgres', () => {
  assert.equal(
    translateSql('SELECT * FROM users WHERE username = ? COLLATE NOCASE'),
    'SELECT * FROM users WHERE LOWER(username) = LOWER($1)',
  )
  assert.equal(
    translateSql('SELECT * FROM users WHERE username LIKE ? COLLATE NOCASE ORDER BY username COLLATE NOCASE'),
    'SELECT * FROM users WHERE LOWER(username) LIKE LOWER($1) ORDER BY LOWER(username)',
  )
  const insert = translateSql('INSERT OR IGNORE INTO memberships (user_id, club_id, role) VALUES (?, ?, ?)')
  assert.match(insert, /INSERT INTO memberships/)
  assert.match(insert, /\$1, \$2, \$3/)
  assert.match(insert, /ON CONFLICT DO NOTHING$/)
  assert.equal(sslFor('postgres://u:p@localhost/db?sslmode=disable'), false)
  const neon = poolConfig('postgres://u:p@ep-example-pooler.neon.tech/neondb?sslmode=require')
  assert.equal(neon.ssl.rejectUnauthorized, false)
  assert.equal(neon.max, 4)
  const schema = pgSchema(SCHEMA)
  assert.match(schema, /id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/)
  assert.doesNotMatch(schema, /COLLATE NOCASE/)
  assert.match(schema, /CREATE TABLE IF NOT EXISTS friend_edges/)
  assert.match(schema, /CREATE TABLE IF NOT EXISTS reports/)
})
